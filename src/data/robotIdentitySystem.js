/**
 * Returns complete visual identity prompt for a given robot ID
 */
export function getRobotVisualPrompt(robotId, customPrompt = '', options = {}) {
  const identity = robotIdentities[robotId] || robotIdentities['R08']
  const env = options.environment || identity.environment
  const style = options.style || 'Cinematic Photorealistic Industrial'
  const camera = options.cameraAngle || 'Dynamic eye-level medium shot'
  const lighting = options.lighting || 'Cinematic factory lighting with dark cyan highlights'
  
  // Clean markdown formatting (** text **, > quotes, _, #) from custom prompt string
  const cleanedCustomPrompt = customPrompt
    .replace(/\*\*/g, '')
    .replace(/^>\s*/gm, '')
    .replace(/[_#`[\]]/g, '')
    .trim()

  if (cleanedCustomPrompt) {
    // Place user's custom prompt at the VERY FRONT so AI image model focuses 100% on the user's intent!
    return `${cleanedCustomPrompt}, ${identity.robotId} ${identity.title}, ${style} style, ${camera}, ${lighting}, ${env} environment, ROBOCORP 25 visual identity.`
  }

  return `${identity.visualPrompt}, ${style} style, ${camera}, ${lighting}, ${env} environment, ROBOCORP 25 visual identity.`
}
